/**
 * Generator of the homepage branch map (SAKEM-111): Indonesia as a dotted map with a point per branch, after the
 * dotted office map of Global DMC (Dzul, 2026-10-27). Run it again rather than editing its output:
 * - public/images/peta/indonesia-dots.svg (repo root): the land as one <path> of dots, navy at 30%
 * - src/lib/branch-map.ts: the canvas size and each branch's point on it
 *
 * `dotted-map@2` is NOT a dependency of this repo (the output is static and the page ships no map code). To run:
 *   DOTTED_MAP=/path/to/node_modules/dotted-map/index.js node scripts/gen-branch-map.mjs
 * with any installed copy of dotted-map@2 (Web Mercator, diagonal grid).
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const mod = await import(pathToFileURL(process.env.DOTTED_MAP ?? 'dotted-map').href);
const DottedMap = mod.default?.default ?? mod.default ?? mod;
const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const REGION = { lat: { min: -11.2, max: 6.4 }, lng: { min: 94.6, max: 141.4 } };
const HEIGHT = 70;
const RADIUS = 0.3;
/** Approximate town centres; the key is the branch's name in `branches` (src/lib/site.ts). */
const PINS = {
  Bandung: { lat: -6.9175, lng: 107.6191 },
  Cililin: { lat: -6.95, lng: 107.4667 },
  Cibodas: { lat: -6.8, lng: 107.62 },
  Cisarua: { lat: -6.81, lng: 107.55 },
  Bojong: { lat: -6.63, lng: 107.53 },
  Cirebon: { lat: -6.7063, lng: 108.557 },
  Purbalingga: { lat: -7.3881, lng: 109.3637 },
  Samarinda: { lat: -0.5022, lng: 117.1536 },
};

const map = new DottedMap({ height: HEIGHT, grid: 'diagonal', region: REGION });
const pts = map.getPoints();
const width = Math.ceil(Math.max(...pts.map((p) => p.x)));
const height = Math.ceil(Math.max(...pts.map((p) => p.y)));
const d = pts
  .map(({ x, y }) => `M${+(x - RADIUS).toFixed(2)},${+y.toFixed(2)}a${RADIUS},${RADIUS} 0 1,0 ${RADIUS * 2},0a${RADIUS},${RADIUS} 0 1,0 -${RADIUS * 2},0`)
  .join('');
const out = resolve(web, '../../public/images/peta');
mkdirSync(out, { recursive: true });
writeFileSync(resolve(out, 'indonesia-dots.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}"><path fill="#0D1F52" fill-opacity="0.3" d="${d}"/></svg>`);

// Each branch projected the way the dots are (Web Mercator over REGION), NOT map.getPin(), which snaps to the nearest
// dot and would stack the West Java branches on one another.
// dotted-map's own canvas is HEIGHT tall and HEIGHT * X_RANGE / Y_RANGE wide (its points never reach the far edges,
// so the measured width and height above are a little smaller; the origin is the same).
const merc = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
const radians = (deg) => (deg * Math.PI) / 180;
const xRange = radians(REGION.lng.max) - radians(REGION.lng.min);
const yRange = merc(REGION.lat.max) - merc(REGION.lat.min);
const canvasWidth = Math.round((HEIGHT * xRange) / yRange);
const project = ({ lat, lng }) => [
  ((radians(lng) - radians(REGION.lng.min)) / xRange) * canvasWidth,
  ((merc(REGION.lat.max) - merc(lat)) / yRange) * HEIGHT,
];
const points = Object.entries(PINS).map(([name, pin]) => {
  const [x, y] = project(pin);
  return `    ${name}: [${+x.toFixed(2)}, ${+y.toFixed(2)}],`;
});
writeFileSync(
  resolve(web, 'src/lib/branch-map.ts'),
  `// GENERATED by scripts/gen-branch-map.mjs (SAKEM-111); do not edit by hand, run the script again.
/** The dotted Indonesia map of the homepage: canvas size, the dots file, and each branch's point on the canvas. */
export const BRANCH_MAP = {
  width: ${width},
  height: ${height},
  dots: '/images/peta/indonesia-dots.svg',
  points: {
${points.join('\n')}
  } as Record<string, [number, number]>,
};
`,
);
console.log(width, height, pts.length);
