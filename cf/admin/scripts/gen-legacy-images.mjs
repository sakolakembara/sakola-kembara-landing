// Writes src/blog/legacy-images.json: the size and content hash of every image of the legacy blog
// (`/blog/images/**`), taken from the image manifest of the public site's asset pipeline. The blog renderer of
// the admin Worker uses it so that saving an imported article again keeps the `srcset`, `width` and `height`
// of its inline images exactly as the build rendered them (docs/cloudflare/admin-blog.md#images).
//
//   pnpm blog:legacy-images
//
// It runs the cheap, manifest-only step of cf/web's pipeline first (it needs `pnpm install` in cf/web, and
// reads the images' headers, never writes a derivative). Commit the result; test/blog-legacy-images.test.ts
// fails when the file differs from what the pipeline knows, and says to run this again.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const adminRoot = path.resolve(here, "..");
const webRoot = path.resolve(adminRoot, "../web");
const manifestFile = path.join(webRoot, "src/generated/image-manifest.json");
const outFile = path.join(adminRoot, "src/blog/legacy-images.json");

if (!existsSync(path.join(webRoot, "node_modules"))) {
  console.error("cf/web has no node_modules: run `pnpm install --frozen-lockfile` in cf/web first.");
  process.exit(1);
}
for (const script of ["scripts/sync-assets.mjs", "scripts/build-assets.mjs"]) {
  const args = script.endsWith("build-assets.mjs") ? [script, "--manifest-only"] : [script];
  const run = spawnSync(process.execPath, args, { cwd: webRoot, stdio: "inherit" });
  if (run.status !== 0) process.exit(run.status ?? 1);
}

const manifest = JSON.parse(readFileSync(manifestFile, "utf8"));
const entries = Object.entries(manifest.images)
  .filter(([urlPath]) => urlPath.startsWith("/blog/images/"))
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const lines = entries.map(([urlPath, entry]) => `    ${JSON.stringify(urlPath)}: [${entry.width}, ${entry.height}, ${JSON.stringify(entry.hash)}]`);
const text = `{\n  "version": 1,\n  "comment": "Generated by scripts/gen-legacy-images.mjs from cf/web's image manifest: [width, height, content hash]. Do not edit.",\n  "images": {\n${lines.join(",\n")}\n  }\n}\n`;
writeFileSync(outFile, text);
console.log(`legacy-images: ${entries.length} images, ${text.length} bytes -> ${path.relative(adminRoot, outFile)}`);
